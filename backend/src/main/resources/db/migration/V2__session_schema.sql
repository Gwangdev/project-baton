CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);

CREATE TABLE jobs (
    id uuid PRIMARY KEY,
    kind varchar(32) NOT NULL,
    target_id bigint NOT NULL,
    generation integer,
    dedup_key varchar(255) NOT NULL UNIQUE,
    status varchar(20) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    available_at timestamptz NOT NULL,
    deadline_at timestamptz NOT NULL,
    lease_token uuid,
    lease_until timestamptz,
    failure_code varchar(60),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT jobs_attempts_nonnegative CHECK (attempts >= 0)
);
CREATE INDEX jobs_status_available_at_idx ON jobs(status, available_at);

CREATE TABLE idempotency_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL REFERENCES users(id),
    method varchar(8) NOT NULL,
    path varchar(300) NOT NULL,
    key uuid NOT NULL,
    request_hash char(64) NOT NULL,
    state varchar(20) NOT NULL,
    target_id bigint,
    http_status integer,
    response_json jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    CONSTRAINT idempotency_requests_scope_key UNIQUE (actor_id, method, path, key),
    CONSTRAINT idempotency_requests_state CHECK (state IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT idempotency_requests_completed_response CHECK (
        state <> 'COMPLETED' OR (http_status IS NOT NULL AND response_json IS NOT NULL)
    )
);

CREATE TABLE audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint,
    action varchar(80) NOT NULL,
    target_type varchar(80) NOT NULL,
    target_id varchar(80) NOT NULL,
    result varchar(32) NOT NULL,
    trace_id varchar(64) NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now()
);

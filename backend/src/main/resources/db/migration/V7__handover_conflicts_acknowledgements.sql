ALTER TABLE handover_items ADD CONSTRAINT handover_items_project_generation_id_key UNIQUE (project_id, generation_id, id);
ALTER TABLE handover_snapshot_records ADD CONSTRAINT handover_snapshot_records_project_generation_id_key UNIQUE (project_id, generation_id, id);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM record_relations
        WHERE relation_type = 'CONFLICTS_WITH'
        GROUP BY project_id, from_record_id HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'V7 requires at most one CONFLICTS_WITH relation per normalized source record; repair duplicate relations before migration';
    END IF;
END $$;

CREATE UNIQUE INDEX record_relations_one_conflict_per_source_key
    ON record_relations(project_id, from_record_id)
    WHERE relation_type = 'CONFLICTS_WITH';

CREATE TABLE handover_item_conflicts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    generation_id bigint NOT NULL,
    handover_item_id bigint NOT NULL,
    relation_id bigint NOT NULL REFERENCES record_relations(id),
    from_snapshot_id bigint NOT NULL,
    to_snapshot_id bigint NOT NULL,
    CONSTRAINT handover_item_conflicts_item_fkey FOREIGN KEY (project_id, generation_id, handover_item_id)
        REFERENCES handover_items(project_id, generation_id, id),
    CONSTRAINT handover_item_conflicts_from_snapshot_fkey FOREIGN KEY (project_id, generation_id, from_snapshot_id)
        REFERENCES handover_snapshot_records(project_id, generation_id, id),
    CONSTRAINT handover_item_conflicts_to_snapshot_fkey FOREIGN KEY (project_id, generation_id, to_snapshot_id)
        REFERENCES handover_snapshot_records(project_id, generation_id, id),
    CONSTRAINT handover_item_conflicts_item_relation_key UNIQUE (handover_item_id, relation_id),
    CONSTRAINT handover_item_conflicts_generation_relation_key UNIQUE (generation_id, relation_id)
);

CREATE TABLE handover_item_acknowledgements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    generation_id bigint NOT NULL,
    item_id bigint NOT NULL,
    user_id bigint NOT NULL REFERENCES users(id),
    acknowledged_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT handover_item_acknowledgements_item_fkey FOREIGN KEY (project_id, generation_id, item_id)
        REFERENCES handover_items(project_id, generation_id, id),
    CONSTRAINT handover_item_acknowledgements_generation_user_key UNIQUE (generation_id, item_id, user_id)
);

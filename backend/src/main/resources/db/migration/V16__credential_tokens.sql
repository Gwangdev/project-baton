-- One-time setup codes for local accounts (README §4.1). A code is shown to the administrator once; only its SHA-256 hash
-- is stored. A user has at most one unused code, so issuing again replaces the earlier one. The code belongs to its user
-- and goes with the user; created_by names the administrator but must not stop that administrator from being deleted.
CREATE TABLE credential_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash char(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX credential_tokens_one_unused_idx ON credential_tokens (user_id) WHERE used_at IS NULL;

CREATE TYPE record_type AS ENUM ('SCHEDULE', 'CHANGE_DECISION', 'COMMITMENT', 'BLOCKER', 'SCOPE_EXCEPTION', 'OPEN_ISSUE');
CREATE TYPE record_trust_status AS ENUM ('AUTO_DRAFT', 'CONFIRMED', 'CORRECTED', 'DISMISSED');
CREATE TYPE record_relation_type AS ENUM ('SUPERSEDES', 'REFERENCES', 'CONFLICTS_WITH');
CREATE TYPE source_channel AS ENUM ('EMAIL', 'APPROVAL', 'MESSENGER', 'MEETING_MINUTES', 'CLOUD_PROJECT_FOLDER');
CREATE TYPE connection_status AS ENUM ('ACTIVE', 'PAUSED', 'DISCONNECTED');
CREATE TYPE source_health AS ENUM ('NORMAL', 'DELAYED', 'FAILED');
CREATE TYPE ingestion_status AS ENUM ('SUCCEEDED', 'DELAYED', 'FAILED');
CREATE TYPE system_role AS ENUM ('USER', 'SYSTEM_ADMIN');
CREATE TYPE project_role AS ENUM ('OUTGOING_OWNER', 'INCOMING_OWNER', 'PROJECT_MANAGER', 'MEMBER');
CREATE TYPE project_status AS ENUM ('PLANNED', 'ON_TRACK', 'AT_RISK', 'CLOSED');
CREATE TYPE handover_status AS ENUM ('REQUESTED', 'GENERATING', 'READY', 'REVIEW_REQUESTED', 'COMPLETED', 'FAILED');
CREATE TYPE handover_item_kind AS ENUM ('OVERVIEW', 'KEY_DECISION', 'CHANGE', 'COMMITMENT', 'OPEN_RISK', 'SCHEDULE', 'FOLLOW_UP');
CREATE TYPE qa_role AS ENUM ('USER', 'ASSISTANT');
CREATE TYPE qa_answer_status AS ENUM ('ANSWERED', 'NO_EVIDENCE', 'FAILED');
CREATE TYPE assessment_status AS ENUM ('NOT_STARTED', 'IN_PROGRESS', 'SUBMITTED');
CREATE TYPE question_type AS ENUM ('MULTIPLE_CHOICE', 'SHORT_ANSWER');

CREATE TABLE organizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    version bigint NOT NULL DEFAULT 0
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES organizations(id),
    employee_no varchar(32) NOT NULL UNIQUE,
    name varchar(60) NOT NULL,
    title varchar(40) NOT NULL,
    email varchar(160) NOT NULL UNIQUE,
    system_role system_role NOT NULL DEFAULT 'USER',
    credential_hash varchar(255),
    auth_provider varchar(16) NOT NULL DEFAULT 'LOCAL',
    external_subject varchar(255),
    external_issuer varchar(500),
    last_signed_in_at timestamptz,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT users_auth_provider CHECK (auth_provider IN ('LOCAL', 'OIDC')),
    CONSTRAINT users_oidc_identity CHECK (
        (auth_provider = 'LOCAL' AND external_subject IS NULL AND external_issuer IS NULL)
        OR (auth_provider = 'OIDC' AND credential_hash IS NULL AND external_subject IS NOT NULL AND external_issuer IS NOT NULL)
    )
);
CREATE INDEX users_organization_id_idx ON users(organization_id);

CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    name varchar(200) NOT NULL,
    delivering_company varchar(120) NOT NULL,
    client_company varchar(120) NOT NULL,
    started_on date NOT NULL,
    ends_on date NOT NULL,
    phase varchar(60) NOT NULL,
    status project_status NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT projects_date_order CHECK (started_on <= ends_on),
    CONSTRAINT projects_id_project_id_key UNIQUE (id, code)
);

CREATE TABLE project_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id),
    user_id bigint NOT NULL REFERENCES users(id),
    project_role project_role NOT NULL,
    joined_on date NOT NULL,
    left_on date,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT project_members_project_user_key UNIQUE (project_id, user_id),
    CONSTRAINT project_members_dates CHECK (left_on IS NULL OR joined_on <= left_on)
);
CREATE INDEX project_members_user_project_idx ON project_members(user_id, project_id);

CREATE TABLE source_connections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id),
    owner_user_id bigint REFERENCES users(id),
    channel source_channel NOT NULL,
    display_name varchar(200) NOT NULL,
    external_ref varchar(300),
    status connection_status NOT NULL DEFAULT 'ACTIVE',
    health source_health NOT NULL DEFAULT 'NORMAL',
    last_collected_at timestamptz,
    last_status ingestion_status,
    last_collected_count integer NOT NULL DEFAULT 0,
    last_failed_count integer NOT NULL DEFAULT 0,
    last_message varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    connector_kind varchar(32) NOT NULL DEFAULT 'FIXTURE',
    checkpoint text,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT source_connections_counts CHECK (last_collected_count >= 0 AND last_failed_count >= 0),
    CONSTRAINT source_connections_owner_channel CHECK (
        (owner_user_id IS NULL AND channel <> 'CLOUD_PROJECT_FOLDER')
        OR (owner_user_id IS NOT NULL AND channel = 'CLOUD_PROJECT_FOLDER')
    ),
    CONSTRAINT source_connections_project_id_id_key UNIQUE (project_id, id)
);
CREATE INDEX source_connections_project_channel_idx ON source_connections(project_id, channel);
CREATE INDEX source_connections_owner_user_id_idx ON source_connections(owner_user_id);

CREATE TABLE record_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_connection_id bigint NOT NULL REFERENCES source_connections(id),
    display_name varchar(200) NOT NULL,
    external_ref varchar(300),
    collected_at timestamptz NOT NULL,
    project_id bigint NOT NULL REFERENCES projects(id),
    external_document_id varchar(300) NOT NULL,
    external_version varchar(128) NOT NULL,
    content_hash char(64) NOT NULL,
    source_body text NOT NULL,
    processing_status varchar(20) NOT NULL DEFAULT 'PENDING',
    failure_code varchar(60),
    source_author_name varchar(120),
    CONSTRAINT record_sources_connection_document_version_key UNIQUE (source_connection_id, external_document_id, external_version),
    CONSTRAINT record_sources_project_id_id_key UNIQUE (project_id, id),
    CONSTRAINT record_sources_project_connection_fkey FOREIGN KEY (project_id, source_connection_id)
        REFERENCES source_connections(project_id, id)
);
CREATE INDEX record_sources_connection_collected_idx ON record_sources(source_connection_id, collected_at);

CREATE TABLE personal_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    project_id bigint NOT NULL REFERENCES projects(id),
    author_id bigint NOT NULL REFERENCES users(id),
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT personal_notes_project_id_id_key UNIQUE (project_id, id)
);
CREATE INDEX personal_notes_project_author_id_idx ON personal_notes(project_id, author_id, id);

CREATE TABLE work_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    project_id bigint NOT NULL REFERENCES projects(id),
    record_source_id bigint,
    source_note_id bigint,
    record_type record_type NOT NULL,
    title varchar(200) NOT NULL,
    summary text NOT NULL,
    original_excerpt text NOT NULL,
    occurred_on date NOT NULL,
    author_id bigint REFERENCES users(id),
    author_name varchar(120) NOT NULL,
    owner_user_id bigint REFERENCES users(id),
    due_on date,
    trust_status record_trust_status NOT NULL DEFAULT 'AUTO_DRAFT',
    confirmed_by bigint REFERENCES users(id),
    confirmed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    version bigint NOT NULL DEFAULT 0,
    source_version varchar(128),
    extraction_index integer NOT NULL DEFAULT 0,
    search_text text NOT NULL,
    CONSTRAINT work_records_source_xor CHECK ((record_source_id IS NULL) <> (source_note_id IS NULL)),
    CONSTRAINT work_records_confirmation_pair CHECK (
        (trust_status IN ('CONFIRMED', 'CORRECTED')) = (confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL)
    ),
    CONSTRAINT work_records_project_id_id_key UNIQUE (project_id, id),
    CONSTRAINT work_records_project_source_fkey FOREIGN KEY (project_id, record_source_id)
        REFERENCES record_sources(project_id, id),
    CONSTRAINT work_records_project_note_fkey FOREIGN KEY (project_id, source_note_id)
        REFERENCES personal_notes(project_id, id),
    CONSTRAINT work_records_source_version_extraction_key UNIQUE (record_source_id, source_version, extraction_index)
);
CREATE INDEX work_records_project_status_occurred_idx ON work_records(project_id, trust_status, occurred_on DESC, id DESC);
CREATE INDEX work_records_project_type_idx ON work_records(project_id, record_type);

CREATE TABLE record_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_record_id bigint NOT NULL REFERENCES work_records(id),
    revision_no integer NOT NULL,
    changed_by bigint NOT NULL REFERENCES users(id),
    change_reason varchar(300) NOT NULL,
    before_summary text NOT NULL,
    after_summary text NOT NULL,
    before_data jsonb NOT NULL,
    after_data jsonb NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT record_revisions_record_revision_key UNIQUE (work_record_id, revision_no)
);

CREATE TABLE record_relations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id),
    from_record_id bigint NOT NULL,
    to_record_id bigint NOT NULL,
    relation_type record_relation_type NOT NULL,
    note varchar(300),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT record_relations_record_relation_key UNIQUE (from_record_id, to_record_id, relation_type),
    CONSTRAINT record_relations_not_self CHECK (from_record_id <> to_record_id),
    CONSTRAINT record_relations_conflict_order CHECK (relation_type <> 'CONFLICTS_WITH' OR from_record_id < to_record_id),
    CONSTRAINT record_relations_project_from_record_fkey FOREIGN KEY (project_id, from_record_id)
        REFERENCES work_records(project_id, id),
    CONSTRAINT record_relations_project_to_record_fkey FOREIGN KEY (project_id, to_record_id)
        REFERENCES work_records(project_id, id)
);
CREATE INDEX record_relations_to_record_id_idx ON record_relations(to_record_id);

CREATE TABLE handovers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    project_id bigint NOT NULL REFERENCES projects(id),
    requested_by bigint NOT NULL REFERENCES users(id),
    outgoing_owner_id bigint NOT NULL REFERENCES users(id),
    incoming_owner_id bigint NOT NULL REFERENCES users(id),
    effective_on date NOT NULL,
    scope_from date NOT NULL,
    scope_to date NOT NULL,
    include_note_derived_records boolean NOT NULL DEFAULT true,
    status handover_status NOT NULL DEFAULT 'REQUESTED',
    progress_percent smallint NOT NULL DEFAULT 0,
    included_count integer NOT NULL DEFAULT 0,
    excluded_count integer NOT NULL DEFAULT 0,
    failure_reason varchar(500),
    requested_at timestamptz NOT NULL DEFAULT now(),
    ready_at timestamptz,
    approved_by bigint REFERENCES users(id),
    completed_at timestamptz,
    CONSTRAINT handovers_scope_order CHECK (scope_from <= scope_to),
    CONSTRAINT handovers_distinct_owners CHECK (outgoing_owner_id <> incoming_owner_id),
    CONSTRAINT handovers_progress_range CHECK (progress_percent BETWEEN 0 AND 100),
    CONSTRAINT handovers_project_id_id_key UNIQUE (project_id, id)
);
CREATE INDEX handovers_project_status_idx ON handovers(project_id, status);
CREATE INDEX handovers_incoming_owner_id_idx ON handovers(incoming_owner_id);
CREATE INDEX handovers_outgoing_owner_id_idx ON handovers(outgoing_owner_id);

CREATE TABLE handover_scope_types (
    handover_id bigint NOT NULL REFERENCES handovers(id),
    record_type record_type NOT NULL,
    PRIMARY KEY (handover_id, record_type)
);

CREATE TABLE handover_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id bigint NOT NULL REFERENCES handovers(id),
    item_kind handover_item_kind NOT NULL,
    work_record_id bigint REFERENCES work_records(id),
    title varchar(200) NOT NULL,
    body text NOT NULL,
    display_order integer NOT NULL,
    is_required boolean NOT NULL DEFAULT false,
    resolved_by_record_id bigint REFERENCES work_records(id),
    resolution_note varchar(300),
    assignee_id bigint REFERENCES users(id),
    due_on date,
    CONSTRAINT handover_items_order_key UNIQUE (handover_id, display_order)
);
CREATE INDEX handover_items_handover_kind_idx ON handover_items(handover_id, item_kind);

CREATE TABLE qa_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id bigint NOT NULL REFERENCES handovers(id),
    session_user_id bigint NOT NULL REFERENCES users(id),
    role qa_role NOT NULL,
    content text NOT NULL,
    answer_status qa_answer_status,
    suggested_contacts varchar(300),
    suggested_documents varchar(300),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX qa_messages_handover_created_idx ON qa_messages(handover_id, created_at);
CREATE INDEX qa_messages_handover_session_id_idx ON qa_messages(handover_id, session_user_id, id);

CREATE TABLE qa_citations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qa_message_id bigint NOT NULL REFERENCES qa_messages(id),
    work_record_id bigint NOT NULL REFERENCES work_records(id),
    trust_status_at_answer record_trust_status NOT NULL,
    is_primary boolean NOT NULL DEFAULT true,
    CONSTRAINT qa_citations_message_record_key UNIQUE (qa_message_id, work_record_id)
);

CREATE TABLE assessments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id bigint NOT NULL UNIQUE REFERENCES handovers(id),
    status assessment_status NOT NULL DEFAULT 'NOT_STARTED',
    pass_threshold smallint NOT NULL DEFAULT 5,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT assessments_pass_threshold_nonnegative CHECK (pass_threshold >= 0)
);

CREATE TABLE assessment_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id bigint NOT NULL REFERENCES assessments(id),
    question_no integer NOT NULL,
    question_type question_type NOT NULL,
    prompt varchar(300) NOT NULL,
    expected_answer varchar(300) NOT NULL,
    linked_record_id bigint NOT NULL REFERENCES work_records(id),
    CONSTRAINT assessment_questions_assessment_number_key UNIQUE (assessment_id, question_no)
);

CREATE TABLE assessment_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id bigint NOT NULL REFERENCES assessments(id),
    attempt_no integer NOT NULL,
    taken_by bigint NOT NULL REFERENCES users(id),
    score smallint NOT NULL DEFAULT 0,
    total smallint NOT NULL,
    submitted_at timestamptz,
    CONSTRAINT assessment_attempts_assessment_number_key UNIQUE (assessment_id, attempt_no),
    CONSTRAINT assessment_attempts_score_range CHECK (score >= 0 AND total >= 0 AND score <= total)
);

CREATE TABLE assessment_answers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id bigint NOT NULL REFERENCES assessment_attempts(id),
    question_id bigint NOT NULL REFERENCES assessment_questions(id),
    answer_text varchar(300) NOT NULL,
    is_correct boolean NOT NULL,
    CONSTRAINT assessment_answers_attempt_question_key UNIQUE (attempt_id, question_id)
);

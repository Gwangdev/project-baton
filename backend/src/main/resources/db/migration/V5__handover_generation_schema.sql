ALTER TABLE handovers ADD COLUMN generation integer NOT NULL DEFAULT 1;
ALTER TABLE handovers ADD COLUMN version bigint NOT NULL DEFAULT 0;
ALTER TABLE handovers ADD COLUMN revision_comment varchar(500);

CREATE TABLE handover_generations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id bigint NOT NULL REFERENCES handovers(id),
    generation integer NOT NULL,
    project_id bigint NOT NULL REFERENCES projects(id),
    created_by bigint NOT NULL REFERENCES users(id),
    status handover_status NOT NULL DEFAULT 'REQUESTED',
    created_at timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    prompt_version varchar(120),
    CONSTRAINT handover_generations_handover_generation_key UNIQUE (handover_id, generation),
    CONSTRAINT handover_generations_project_id_id_key UNIQUE (project_id, id),
    CONSTRAINT handover_generations_project_handover_fkey FOREIGN KEY (project_id, handover_id)
        REFERENCES handovers(project_id, id)
);

CREATE TABLE handover_snapshot_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation_id bigint NOT NULL REFERENCES handover_generations(id),
    project_id bigint NOT NULL REFERENCES projects(id),
    work_record_id bigint NOT NULL REFERENCES work_records(id),
    record_version bigint NOT NULL,
    content_json jsonb NOT NULL,
    trust_status record_trust_status NOT NULL,
    captured_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT handover_snapshot_records_generation_record_key UNIQUE (generation_id, work_record_id),
    CONSTRAINT handover_snapshot_records_project_generation_fkey FOREIGN KEY (project_id, generation_id)
        REFERENCES handover_generations(project_id, id),
    CONSTRAINT handover_snapshot_records_project_record_fkey FOREIGN KEY (project_id, work_record_id)
        REFERENCES work_records(project_id, id)
);
